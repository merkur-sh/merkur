export const SPECULATIVE_ASCII_FIRST = 0x20;
export const SPECULATIVE_ASCII_LAST = 0x7e;
export const SPECULATIVE_ASCII_COUNT = SPECULATIVE_ASCII_LAST - SPECULATIVE_ASCII_FIRST + 1;

/** One glyph id per printable ASCII codepoint, 0 for one that draws nothing. */
export const SPECULATIVE_GLYPH_ENTRIES_LENGTH = SPECULATIVE_ASCII_COUNT;
export const SPECULATIVE_GLYPH_ENTRIES_BYTES =
  SPECULATIVE_GLYPH_ENTRIES_LENGTH * Int32Array.BYTES_PER_ELEMENT;

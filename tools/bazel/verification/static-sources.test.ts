test('temporary namespace substitution restores held original without modifying a foreign replacement', async () => {
  const parent = mkdtempSync(path.join(os.tmpdir(), 'merkur-captured-static-substitution-'));
  try {
    const sourceRoot = path.join(parent, 'source');
    const tree = path.join(parent, 'tree');
    const root = path.join(parent, 'private');
    for (const directory of [sourceRoot, tree, root]) mkdirSync(directory);
    for (const directory of [sourceRoot, tree])
      writeFileSync(path.join(directory, 'module.js'), 'original');
    const source = manifestFromInventory(sourceRoot, ['module.js'], 'commit');
    await expect(
      withCapturedSourceTree({ tree, root, source }, async () => {
        const target = path.join(root, 'module.js');
        const original = lstatSync(target);
        expect(() =>
          withStaticSources(
            root,
            source,
            [member('module.js')],
            () => true,
            () => {
              renameSync(target, path.join(root, 'moved.js'));
              writeFileSync(target, 'foreign');
            },
          ),
        ).toThrow();
        expect(readFileSync(target, 'utf8')).toBe('foreign');
        expect(readFileSync(path.join(root, 'moved.js'), 'utf8')).toBe('original');
        expect(lstatSync(path.join(root, 'moved.js')).ino).toBe(original.ino);
      }),
    ).rejects.toThrow();
    expect(readFileSync(path.join(root, 'module.js'), 'utf8')).toBe('foreign');
  } finally {
    rmSync(parent, { recursive: true, force: true });
  }
});

